/**
 * The only CSS we emit. It deliberately holds no colors: one stylesheet is shared
 * by every window while colors come from per-workspace settings, so every color
 * travels as a custom property the painter sets on exactly the rows it styled.
 */

/**
 * Styling for the selected/focused row's label + twistie, the inline rename box,
 * and hover brightening. It's non-destructive (reverts on deselect) and, with
 * `!important`, overrides the inline decoration colors so badges stay readable on
 * a bright selection.
 */
export function buildCss(): string {
  const header =
    '/* Auto-generated by premium-explorer. Do not edit — regenerated from settings. */\n' +
    '/* Backgrounds, hover and selection are painted by premium-explorer.js. */\n';

  // The inline rename box. VS Code paints it with the theme's own input colors, so on
  // a colored row it lands as a foreign slab with the row's fill left showing as a
  // stub in the indent gutter. Instead the row itself shifts a step off its usual
  // color while it is being edited (see `EDIT_SHIFT` in the script) and the box gets
  // out of the way entirely — transparent, so the shifted fill and the watermark over
  // it carry straight through, with a border to mark where the typing goes. The
  // script publishes that border and a foreground that reads against the shifted
  // color; the fallbacks leave rows we don't paint with the theme's own input look.
  //
  // This has to be applied from here rather than inline, because
  // `InputBox.applyStyles()` rewrites its own inline colors on every validation pass
  // and would win against a script that set them directly — `!important` from a
  // stylesheet outranks any inline declaration. `caret-color` follows `color`, so the
  // caret is lit by the same rule.
  const editRow = 'body.fc-active .explorer-folders-view .monaco-list-row.fc-editing';
  const editCss =
    '\n/* Inline rename box: the row itself shifts, the box just marks the field. */\n' +
    `${editRow} .monaco-inputbox {\n` +
    '\tbackground-color: transparent !important;\n' +
    '\tborder-color: transparent !important;\n' +
    '\tcolor: var(--fc-edit-fg, var(--vscode-input-foreground)) !important;\n' +
    '}\n' +
    `${editRow} .monaco-inputbox input {\n` +
    '\tbackground-color: var(--fc-edit-field, var(--vscode-input-background)) !important;\n' +
    '\tcolor: var(--fc-edit-fg, var(--vscode-input-foreground)) !important;\n' +
    '\toutline: 1px solid var(--fc-edit-border, var(--vscode-focusBorder)) !important;\n' +
    '\toutline-offset: -1px !important;\n' +
    '\tborder-radius: 3px;\n' +
    '}\n';

  // `body.fc-active` is set by the injected script only in a window whose workspace
  // is configured, so this selected-label styling doesn't apply in other workspaces.
  // Match only `.selected` (not a stale `.focused` row), and color the whole row
  // contents — not just `.monaco-icon-label` — so a decoration badge stays this
  // color. `.monaco-tl-twistie` (the expand/collapse chevron) is listed too.
  // `.fc-editing` is set by the injected script on a row showing the inline rename
  // box. Its `<input>` is inside `.monaco-tl-contents`, so an `!important` color
  // here would apply to the text being typed — and to the caret, which follows
  // `color` — leaving the rename invisible. Stand down for those rows.
  // `.fc-sel` is set by the script on exactly the rows it painted a selection fill
  // on. Without it this rule fires on every selected row in a configured workspace
  // while the fill reaches only the ones inside a coloured folder — so a row outside
  // one got this colour over the theme's own selection background, which is how a
  // black label landed on a dark grey row.
  // Neither the weight nor the color can be a literal here. This is one stylesheet
  // shared by every window, and both come from per-workspace settings — writing
  // this window's answer into it is what let one workspace's `"invert"` erase
  // another's `"#ffffff"`. So the script decides per row: `.fc-sel-bold` and
  // `.fc-sel-text` are set on exactly the rows it styled, and the color travels as
  // `--fc-sel-fg`. A row it set neither on is not matched by either rule.
  const row = 'body.fc-active .explorer-folders-view .monaco-list-row.selected.fc-sel:not(.fc-editing)';
  const selectors = (marker: string): string => [
    `${row}${marker} .monaco-tl-contents`,
    `${row}${marker} .monaco-tl-contents *`,
    `${row}${marker} .monaco-tl-twistie`,
  ].join(',\n');

  // Hover brightening. The painter used to repaint the whole pane on every
  // mouseover just to swap each layer's hover variant in — with watermark
  // data-URIs in play that made moving the mouse drag megabytes of string work
  // per paint. Instead the script publishes the brighter colors up front as
  // custom properties on exactly the rows whose fill/pill is their own (never a
  // selection or rename fill — see setHoverVars in inject.js), and the
  // browser's own `:hover` does the swap with no script at all. `!important`
  // because the resting color is an inline style.
  const hoverRow = 'body.fc-active .explorer-folders-view .monaco-list-row';
  const hoverCss =
    '\n/* Hover brightening: applied by CSS so mouse moves never repaint. */\n' +
    `${hoverRow}.fc-hover-bg:hover {\n\tbackground-color: var(--fc-bg-hover) !important;\n}\n` +
    // `background`, not `background-color`: a pill fill may be a baked gradient
    // string, and its hover variant is one too — the shorthand takes both.
    `${hoverRow}.fc-hover-pill:hover .label-name {\n\tbackground: var(--fc-pill-hover) !important;\n}\n`;

  // A selected row whose pill kept its own fill keeps its own label text too
  // (`.fc-pill-own`, set by the painter): the selection text color is picked
  // against the selection fill, which is not what this label sits on. The pill's
  // normal color travels as `--fc-pill-fg`; without one the theme's foreground
  // is the color the unselected label had. Declared after the `.fc-sel-text`
  // rule and one class more specific, so it wins exactly on the label.
  const pillOwn = [
    `${row}.fc-sel-text.fc-pill-own .label-name`,
    `${row}.fc-sel-text.fc-pill-own .label-name *`,
  ].join(',\n');

  // Git's status marks (EM-96). VS Code renders the status *letter* and the folder
  // *dot* as `::after` content on `.monaco-icon-label`, coloured by a class whose
  // name is a runtime hash — so neither can be styled inline, and no stylesheet can
  // name the hash. What it can name is the two stable classes VS Code puts beside
  // it: `.monaco-decoration-text-badge` is the letter (a file), and a
  // `.monaco-decoration-badge` without it is the dot (a folder). The painter decides
  // per row and publishes the colours as custom properties, exactly like
  // `--fc-sel-fg`, so one stylesheet still serves every window.
  //
  // `!important` on the colours because VS Code's own `::after` rule sets `color`;
  // the plate and border are ours alone and need no weight. `box-sizing` keeps the
  // border from growing the letter, and the padding plus the centring below are the
  // chip's whole geometry — VS Code's horizontal margins are left alone so the row's
  // layout holds.
  const gitRow = 'body.fc-active .explorer-folders-view .monaco-list-row';
  const letter = (marker: string): string =>
    `${gitRow}${marker} .monaco-icon-label.monaco-decoration-text-badge::after`;
  const dot = (marker: string): string =>
    `${gitRow}${marker} .monaco-icon-label.monaco-decoration-badge:not(.monaco-decoration-text-badge)::after`;
  const gitCss =
    "\n/* Git status marks lifted clear of a painted row (see setGitVars). */\n" +
    `${letter('.fc-git-ink')} {\n\tcolor: var(--fc-git-fg) !important;\n}\n` +
    // The dot is a codicon at opacity .4, which would undo any lift — so a row we
    // took over gets it at full strength, with a halo in the plate colour standing
    // in for the design's "dark ring".
    `${dot('.fc-git-ink')} {\n` +
    '\tcolor: var(--fc-git-dot, var(--fc-git-fg)) !important;\n' +
    '\topacity: 1 !important;\n' +
    '\ttext-shadow: 0 0 2px var(--fc-git-plate, transparent);\n' +
    '}\n' +
    // The chip itself: a small square plate with the letter centred in it, as the
    // design draws it. `inline-flex` is what centres a single character in a box
    // this size.
    //
    // The vertical placement is the whole reason this rule carries margins at all.
    // `.monaco-icon-label` is a flex row and the badge is one of its items, and
    // VS Code's own `.monaco-icon-label:after { margin: auto 16px 0 5px }` gives it
    // an **auto top margin against a zero bottom one**. A flex item's auto margin
    // eats the free space on that side, so a box shorter than the 22px row is
    // pushed flush to the row's bottom edge: harmless for VS Code's bare 11px
    // letter, but our 15px plate then sat on the row boundary and bled into the row
    // below (EM-96 — the auto margin is why devtools reports a 7px top here and 0px
    // on an unstyled row). Zeroing both margins is what lets `align-self` centre it;
    // the horizontal margins stay as VS Code set them, so the row's layout and the
    // right-hand gutter do not shift under us.
    `${letter('.fc-git-chip')},\n${letter('.fc-git-outline')} {\n` +
    '\tbox-sizing: border-box;\n' +
    '\tdisplay: inline-flex;\n' +
    '\talign-items: center;\n' +
    '\tjustify-content: center;\n' +
    '\talign-self: center;\n' +
    '\tmin-width: 15px;\n' +
    '\theight: 15px;\n' +
    '\tmargin-top: 0;\n' +
    '\tmargin-bottom: 0;\n' +
    '\tpadding: 0 2px;\n' +
    '\tline-height: 1;\n' +
    '\tborder-radius: 3px;\n' +
    '\tborder: 1px solid var(--fc-git-border, transparent);\n' +
    '}\n' +
    `${letter('.fc-git-chip')} {\n\tbackground: var(--fc-git-plate, transparent);\n}\n` +
    `${letter('.fc-git-outline')} {\n\tbackground: transparent;\n}\n` +
    // `gitMarkStyle: "none"` hides the letter and the dot; the filename still lifts.
    `${letter('.fc-git-off')},\n${dot('.fc-git-off')} {\n\tdisplay: none !important;\n}\n`;

  return header + editCss + hoverCss + gitCss +
    '\n/* Selected-row label + twistie. */\n' +
    selectors('.fc-sel-bold') + ' {\n\tfont-weight: bold !important;\n}\n' +
    selectors('.fc-sel-text') + ' {\n\tcolor: var(--fc-sel-fg) !important;\n}\n' +
    '\n/* ...except a label on a pill that kept its own fill (see fc-pill-own). */\n' +
    pillOwn + ' {\n\tcolor: var(--fc-pill-fg, var(--vscode-foreground)) !important;\n}\n';
}
