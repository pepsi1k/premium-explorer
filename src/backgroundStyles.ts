/**
 * Generates and delivers the files the workbench loads to paint Explorer
 * **backgrounds** — something the VS Code API cannot do. Three files: the static
 * painter JS (media/inject.js, shipped verbatim), a small static CSS, and the
 * baked per-workspace config as JSON, which the painter fetches fresh on every
 * boot. This module only orchestrates; the real work lives next door:
 *
 *   - coloredFolders.ts  resolves the rules and bakes each folder's layers
 *   - workspaceState.ts  keeps the per-workspace unions behind the global file
 *   - generatedCss.ts    the static CSS (selected label, rename box, hover)
 *   - watermarkArt.ts    turns a watermark symbol into drawable artwork
 *
 * [injection.ts](src/injection.ts) is what gets the files loaded, by patching
 * `workbench.html`. See README.md for the full rationale.
 */
import * as vscode from 'vscode';
import { FolderColorerConfig } from './config';
import { resolveColoredFolders, bakeAll } from './coloredFolders';
import {
  InjectedConfig,
  buildSelection,
  groupByWorkspace,
  mergeWorkspaceColors,
  mergeWorkspaceSelection,
} from './workspaceState';
import { buildCss } from './generatedCss';
import { inspect as inspectWorkbench, mirror as mirrorWorkbench } from './workbenchPatch';

const CSS_FILE = 'premium-explorer.css';
const JS_FILE = 'premium-explorer.js';
const JSON_FILE = 'premium-explorer.json';

/** Extension version the files in global storage were last generated by. */
const GENERATED_VERSION_STATE = 'premiumExplorer.generatedVersion';

interface GeneratedFiles {
  cssUri: vscode.Uri;
  jsUri: vscode.Uri;
  jsonUri: vscode.Uri;
  count: number;
}

/**
 * Generate and write all three files. Always writes (empty when the rules match
 * nothing, so removing rules clears the backgrounds on reload); `count` is how
 * many folders this workspace colored.
 */
export async function writeBackgroundFiles(
  context: vscode.ExtensionContext,
  config: FolderColorerConfig,
): Promise<GeneratedFiles> {
  // When disabled, write inert files. The workbench loads these files independently
  // of the extension, so `premiumExplorer.enabled` has to clear them here —
  // otherwise the last-generated backgrounds/selection keep painting.
  if (!config.enabled) {
    return writeFiles(context,
      '/* premium-explorer disabled (premiumExplorer.enabled = false). */\n',
      '// premium-explorer disabled (premiumExplorer.enabled = false).\n',
      // An inert config, not an empty file: the painter fetches and parses this,
      // and `workspaces: {}` is its own "paint nothing anywhere" state.
      JSON.stringify({ workspaces: {}, selections: {} }) + '\n',
      0,
    );
  }

  // Resolve this window's colored folders (each already expanded into its baked
  // layers) and attribute each to the workspace folder that owns it, then merge
  // into the persisted cross-workspace union so other workspaces' colors survive
  // (and this workspace's stale ones are cleared).
  const coloredFolders = await resolveColoredFolders(config, context.extensionUri.fsPath);
  const thisWindow = groupByWorkspace(coloredFolders, bakeAll(coloredFolders));
  const workspaces = mergeWorkspaceColors(context, thisWindow);

  const selection = buildSelection(config);
  const css = buildCss();
  const js = await buildInjectedScript(context);
  const injected: InjectedConfig = {
    workspaces,
    selections: mergeWorkspaceSelection(context, selection),
    // The fallback for a workspace that is in the colors union but not yet in the
    // selection one — its window last generated before selections were split per
    // workspace. It self-heals the next time that window generates.
    selection,
  };

  // `count` is what this workspace matched (drives the "no folders" warning).
  const count = Object.values(thisWindow).reduce((n, m) => n + Object.keys(m).length, 0);
  return writeFiles(context, css, js, JSON.stringify(injected), count);
}

/**
 * The static browser script (media/inject.js), shipped verbatim. The baked config
 * is NOT prepended: the workbench serves the script from Chromium's cache across
 * window reloads, so anything riding inside it went stale until a full app restart
 * (EM-86). The config travels as its own JSON file instead, which the script
 * fetches with `cache: "no-store"` on every boot.
 */
async function buildInjectedScript(context: vscode.ExtensionContext): Promise<string> {
  const templateUri = vscode.Uri.joinPath(context.extensionUri, 'media', 'inject.js');
  const template = Buffer.from(await vscode.workspace.fs.readFile(templateUri)).toString('utf8');
  return '// Auto-generated by premium-explorer. Do not edit — regenerated from settings.\n' + template;
}

/**
 * Write the generated files into global storage and return their URIs.
 *
 * Global storage stays the source of truth, and the workbench patch copies from
 * it. Refreshing the patched copy here means every caller that regenerates — a
 * settings change, an extension update, the command run by hand — keeps the live
 * copy in step without having to know the patch exists.
 */
async function writeFiles(
  context: vscode.ExtensionContext,
  css: string,
  js: string,
  json: string,
  count: number,
): Promise<GeneratedFiles> {
  await vscode.workspace.fs.createDirectory(context.globalStorageUri);
  const cssUri = vscode.Uri.joinPath(context.globalStorageUri, CSS_FILE);
  const jsUri = vscode.Uri.joinPath(context.globalStorageUri, JS_FILE);
  const jsonUri = vscode.Uri.joinPath(context.globalStorageUri, JSON_FILE);
  await vscode.workspace.fs.writeFile(cssUri, Buffer.from(css, 'utf8'));
  await vscode.workspace.fs.writeFile(jsUri, Buffer.from(js, 'utf8'));
  await vscode.workspace.fs.writeFile(jsonUri, Buffer.from(json, 'utf8'));
  // Stamp which version wrote these, so regenerateIfStale() has a baseline. Doing
  // it here keeps the stamp describing the files actually on disk, whichever
  // caller produced them.
  await context.globalState.update(
    GENERATED_VERSION_STATE,
    String(context.extension?.packageJSON?.version ?? ''),
  );
  mirrorToWorkbench(cssUri.fsPath, jsUri.fsPath, jsonUri.fsPath);
  return { cssUri, jsUri, jsonUri, count };
}

/**
 * Refresh the patched workbench's copy of the files, if we are the one painting.
 *
 * Deliberately silent on failure. Regenerating has to keep working for someone who
 * has never turned painting on, and a patch that a VS Code update has wiped is
 * worth one prompt on activation — not a warning every time a setting moves.
 */
function mirrorToWorkbench(css: string, js: string, json: string): void {
  const status = inspectWorkbench();
  if (status.state !== 'patched') {
    return;
  }
  try {
    mirrorWorkbench(status.workbench, { css, js, json });
  } catch {
    // Surfaced by the activation check and the enable command instead.
  }
}

/**
 * Once the files exist, keep them current when settings change so tweaks to
 * rules/palette/opacity/selection apply on the next window reload — no command
 * needed.
 */
export async function regenerateIfConfigured(
  context: vscode.ExtensionContext,
  config: FolderColorerConfig,
): Promise<void> {
  const cssUri = vscode.Uri.joinPath(context.globalStorageUri, CSS_FILE);
  try {
    await vscode.workspace.fs.stat(cssUri);
  } catch {
    return; // not set up yet — nothing to keep in sync
  }
  await writeBackgroundFiles(context, config);
  const choice = await vscode.window.showInformationMessage(
    'Premium Explorer: background styles updated. Reload to apply.',
    'Reload Window',
  );
  if (choice === 'Reload Window') {
    await vscode.commands.executeCommand('workbench.action.reloadWindow');
  }
}

/**
 * Re-emit the generated files after an extension update.
 *
 * The JS file embeds media/inject.js **verbatim**, so a new version of the painter
 * only reaches the workbench when the file is rewritten — and the only thing that
 * rewrites it is a settings change (see {@link regenerateIfConfigured}) or the
 * command run by hand. An update therefore ships a new painter that nothing
 * installs: global storage keeps serving the script from whichever version last
 * happened to write it, indefinitely. Stamping the version we generated for, and
 * refreshing when it moves, is what makes an update actually take effect.
 */
export async function regenerateIfStale(
  context: vscode.ExtensionContext,
  config: FolderColorerConfig,
): Promise<void> {
  const version = String(context.extension?.packageJSON?.version ?? '');
  if (!version || context.globalState.get<string>(GENERATED_VERSION_STATE) === version) {
    return;
  }
  const cssUri = vscode.Uri.joinPath(context.globalStorageUri, CSS_FILE);
  try {
    await vscode.workspace.fs.stat(cssUri);
  } catch {
    // Never generated, so there is nothing stale to refresh. Leave the stamp unset
    // too: the first real generate should be the thing that records a version.
    return;
  }
  await writeBackgroundFiles(context, config); // stamps GENERATED_VERSION_STATE
  const choice = await vscode.window.showInformationMessage(
    `Premium Explorer ${version}: regenerated the injected files. Reload to apply.`,
    'Reload Window',
  );
  if (choice === 'Reload Window') {
    await vscode.commands.executeCommand('workbench.action.reloadWindow');
  }
}
